/* Service worker: precache the whole site so it works on a field with no signal.
   Generated by build.mjs, which fills in the precache list and version at build time. */
const VERSION = '__VERSION__';
const CACHE = `germany-${VERSION}`;
const PRECACHE = __PRECACHE__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      const urls = PRECACHE.map((p) => new URL(p, self.registration.scope).toString());
      // Add one at a time so a single missing file doesn't fail the install.
      await Promise.all(urls.map((u) => cache.add(u).catch(() => null)));
      await self.skipWaiting();
    })
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only handle same-origin requests; YouTube, fonts etc. go straight to the network.
  if (url.origin !== self.location.origin) return;
  // Network first (so updates show up right away), falling back to the cache
  // when offline or when the network is slow — the field is a dead zone.
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(req, { ignoreSearch: true });
      const timeout = new Promise((resolve) => setTimeout(() => resolve(null), cached ? 3000 : 15000));
      try {
        const res = await Promise.race([fetch(req), timeout]);
        if (res && res.ok) {
          cache.put(req, res.clone());
          return res;
        }
        if (cached) return cached;
        return res || fetch(req);
      } catch {
        return cached || Response.error();
      }
    })()
  );
});
